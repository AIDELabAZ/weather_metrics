"""
Simplified overview of the fixed-label classifier for the full-corpus
(3,755-paper) extraction runs, with one classifier setting (default: the
Qwen3 8B pair + the field-neutral "concept" judge gate, approach C).

Writes to <OneDrive>/weather_iv_lit/analysis/classifier/<OUT_NAME>/:
  README.md
  entries_rainfall.csv     one row per unique entry (rainfall side)
  entries_endogenous.csv   one row per unique entry (endogenous side)
  sankeys/sankey_full_<run>.png (+ _wide.png); details/ has html, eps and
          the pipeline's own audit / cluster / residual-share CSVs

Entry columns, in order: entry, category, n_occurrences, runs, embed_sim,
embed_category, rerank_score, rerank_category, rerank_runner_up_score,
rerank_runner_up, judge_score, judge_decision.

Usage (from lit_review/):
  DYLD_FALLBACK_LIBRARY_PATH=/opt/homebrew/lib python3 analysis/classifier_overview.py [tables] [sankeys]
"""

import os
import sys
from collections import Counter, defaultdict

import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import export_classifier_tables as ect
import fixed_label_classifier as flc
import sankey_full_corpus_baselines as full
import sankey_iv_clustering as sic
from sankey_taxonomy import unclassifiable_label

BACKBONE = os.environ.get("OVERVIEW_BACKBONE", "qwen3-8b")
GATE = os.environ.get("OVERVIEW_GATE", "concept")
EXCLUDE_RUNS = {"claude"}
RUNS = {k: d for k, d in full.BASELINES.items() if k not in EXCLUDE_RUNS}
# Default setting (8B + concept gate) writes to classifier/8b/; any other
# setting gets a descriptive folder name so it can't overwrite 8b/.
_DEFAULT = BACKBONE == "qwen3-8b" and GATE == "concept"
OUT_NAME = "8b" if _DEFAULT else f"overview_{BACKBONE}_{GATE}_full_corpus"
OUT_DIR = os.path.join("/Users/kieran/Library/CloudStorage/OneDrive-UniversityofArizona/weather_iv_lit/analysis/classifier",
                       OUT_NAME)
SIDE_FILES = {"Rainfall Metrics": "entries_rainfall.csv", "Endogenous Variables": "entries_endogenous.csv"}


def occurrences() -> dict[str, dict[str, Counter]]:
    """{side: {entry: Counter(run -> n)}} over the selected full-corpus runs."""
    occ = {side: defaultdict(Counter) for side, _, _ in ect.SIDES}
    for key, subdir in RUNS.items():
        full.set_paths(key, subdir)
        if not os.path.exists(sic.MERGED_CSV):
            print(f"  skip (missing input): {sic.MERGED_CSV}")
            continue
        raw = sic.load_rainfall_papers(sic.MERGED_CSV)
        for side, col, req in ect.SIDES:
            exp, _ = sic.expand_column(raw, col, requires_rainfall=req)
            for entry, n in exp["entry"].value_counts().items():
                occ[side][entry][key] += n
    return occ


def judge_decision(row, side) -> str:
    if GATE == "reranker":
        return "pass" if row["valid_score"] >= flc.GATE_THRESHOLD else "Unclassifiable"
    if row["unclassifiable_rule"]:
        return f"Unclassifiable (rule: {row['unclassifiable_rule']})"
    if GATE == "concept" and row["entry"].strip().lower() in flc.KNOWN_ABBREVIATIONS:
        return "pass (known abbreviation)"
    return "Unclassifiable" if row["label"] == unclassifiable_label(side) else "pass"


def write_tables(occ) -> None:
    for side, _, _ in ect.SIDES:
        entries = sorted(occ[side])
        _, a = flc.classify(entries, side, backbone=BACKBONE, gate=GATE)
        a = a.set_index("entry", drop=False)
        df = pd.DataFrame({
            "entry": entries,
            "category": a.loc[entries, "label"].values,
            "n_occurrences": [sum(occ[side][e].values()) for e in entries],
            "runs": ["; ".join(f"{r}:{n}" for r, n in sorted(occ[side][e].items(), key=lambda x: -x[1]))
                     for e in entries],
            "embed_sim": a.loc[entries, "embed_top1_sim"].round(3).values,
            "embed_category": a.loc[entries, "embed_top1"].values,
            "rerank_score": a.loc[entries, "best_score"].round(3).values,
            "rerank_category": a.loc[entries, "best_category"].values,
            "rerank_runner_up_score": a.loc[entries, "top2_score"].round(3).values,
            "rerank_runner_up": a.loc[entries, "top2"].values,
            "judge_score": a.loc[entries, "valid_score"].round(3).values,
            "judge_decision": [judge_decision(a.loc[e], side) for e in entries],
        })
        df = df.sort_values(["n_occurrences", "entry"], ascending=[False, True])
        df.to_csv(os.path.join(OUT_DIR, SIDE_FILES[side]), index=False)
        print(f"  {side}: {len(df)} entries -> {SIDE_FILES[side]}")


README = """# Classifier overview: {backbone}, {gate} gate, full-corpus runs

Generated by `analysis/classifier_overview.py`. Runs: {runs}. No hand review applied.

## Pipeline (per unique entry)
1. **Embedding** (Qwen3-Embedding): closest category by cosine similarity -> `embed_category`, `embed_sim`.
   Shown for comparison only; it does not affect the label or limit the reranker's choices.
2. **Reranker** (Qwen3-Reranker): scores the entry against every real category and Other. The highest score wins
   -> `rerank_category` / `rerank_score`; second place -> `rerank_runner_up` / `rerank_runner_up_score`.
3. **Gate** ("can this entry be interpreted?"): {gate_note}
   -> `judge_score` (P(yes), 0-1; below 0.5 = Unclassifiable) and `judge_decision`.
4. `category` = `rerank_category` if the gate passes, otherwise Unclassifiable.

## Entry files (entries_rainfall.csv, entries_endogenous.csv)
One row per unique entry, most frequent first.

| Column | Meaning |
|---|---|
| entry | Cleaned entry as extracted |
| category | Final label: a real category, Other, or Unclassifiable |
| n_occurrences | Times the entry appears across the runs below |
| runs | Which runs extracted it, with counts (run:n) |
| embed_sim / embed_category | Embedding step: closest category and its cosine similarity (relative, not a probability) |
| rerank_score / rerank_category | Reranker winner and its P(yes) |
| rerank_runner_up_score / rerank_runner_up | Second place; a small gap to the winner is a close call |
| judge_score | Gate P(yes) that the entry is interpretable (still computed when a rule fired) |
| judge_decision | pass, pass (known abbreviation), Unclassifiable, or Unclassifiable (rule: ...) |

## Sankeys
`sankeys/sankey_full_<run>.png` (+ `_wide.png`): Other is shown, Unclassifiable is excluded; its share is in
`sankeys/details/residual_shares_full_<run>.csv`.
"""

GATE_NOTES = {
    "concept": "rules first (short codes, letter-digit codes, corrupted text; a fixed list of generic labels such "
               "as quantity, driving factor, dummy, lagged dependent variable (fixed_label_classifier.GENERIC_LABELS); "
               "on the rainfall side also the bare names rainfall / rain / precipitation and their squares), then a "
               "Qwen3 chat model of the same size is asked whether the name refers to a recognizable concept or "
               "measure (field-neutral question, v3 prompt). Allow-listed abbreviations (gdp, co, pm10, tx10p, ...) "
               "always pass.",
    "judge": "rules for codes / corrupted text, then a Qwen3 chat model asked whether the name identifies a specific "
             "measure.",
    "reranker": "the reranker scores the entry against a definition of an interpretable entry.",
}


def run_sankeys() -> None:
    flc.BACKBONE, flc.GATE = BACKBONE, GATE
    folder = os.path.join(OUT_DIR, "sankeys")
    details = os.path.join(folder, "details")
    os.makedirs(details, exist_ok=True)
    for key, subdir in RUNS.items():
        full.set_paths(key, subdir)
        if not os.path.exists(sic.MERGED_CSV):
            continue
        stem = f"full_{key}"
        sic.OUTPUT_PNG_ENDOG = os.path.join(folder, f"sankey_{stem}.png")
        sic.OUTPUT_PNG_WIDE_ENDOG = os.path.join(folder, f"sankey_{stem}_wide.png")
        sic.OUTPUT_HTML_ENDOG = os.path.join(details, f"sankey_{stem}.html")
        sic.OUTPUT_EPS_ENDOG = os.path.join(details, f"sankey_{stem}.eps")
        sic.CLUSTER_SUMMARY_ENDOG = os.path.join(details, f"cluster_summary_endog_{stem}.csv")
        sic.REJECTED_ENTRIES_CSV = os.path.join(details, f"rejected_entries_{stem}.csv")
        sic.RELATIONSHIPS_RAW_ENDOG_CSV = os.path.join(details, f"relationships_raw_endog_{stem}.csv")
        sic.RELATIONSHIPS_CATEGORIZED_ENDOG_CSV = os.path.join(details, f"relationships_categorized_endog_{stem}.csv")
        sic.CLASSIFIER_AUDIT_CSV = os.path.join(details, f"classifier_audit_{stem}.csv")
        print(f"\n===== Sankey {BACKBONE} / {GATE} / {stem} =====", flush=True)
        sic.main()


def main():
    steps = sys.argv[1:] or ["tables", "sankeys"]
    os.makedirs(OUT_DIR, exist_ok=True)
    with open(os.path.join(OUT_DIR, "README.md"), "w", encoding="utf-8") as f:
        f.write(README.format(backbone=BACKBONE, gate=GATE + (f" ({flc.CONCEPT_PROMPT} prompt)" if GATE == "concept" else ""),
                              runs=", ".join(RUNS), gate_note=GATE_NOTES[GATE]))
    if "tables" in steps:
        write_tables(occurrences())
    if "sankeys" in steps:
        run_sankeys()
    print(f"\nOutputs -> {OUT_DIR}")


if __name__ == "__main__":
    main()
